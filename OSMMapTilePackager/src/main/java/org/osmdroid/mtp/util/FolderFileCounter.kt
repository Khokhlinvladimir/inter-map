package org.osmdroid.mtp.util

import java.io.File

object FolderFileCounter {
    // ===========================================================
    // Constants
    // ===========================================================
    // ===========================================================
    // Fields
    // ===========================================================
    // ===========================================================
    // Constructors
    // ===========================================================
    // ===========================================================
    // Getter & Setter
    // ===========================================================
    // ===========================================================
    // Methods from SuperClass/Interfaces
    // ===========================================================
    // ===========================================================
    // Methods
    // ===========================================================
    /**
     * @return `true` on success, `false` otherwise.
     */
    fun getTotalRecursiveFileCount(pFolder: File): Int {
        val children = pFolder.listFiles()

        var tmpCnt = 0
        for (c in children!!) {
            if (c.isDirectory()) {
                tmpCnt += getTotalRecursiveFileCount(c)
            } else {
                tmpCnt++
            }
        }
        return tmpCnt
    } // ===========================================================
    // Inner and Anonymous Classes
    // ===========================================================
}
